/**
 * Standard SKU generator for RaptorERP products.
 * Generates clean, unique, professional ERP product SKUs.
 */

export function generateClientSku(
  name?: string | null,
  existingSkus: (string | null | undefined)[] = [],
  prefix = 'PRD'
): string {
  const existingSet = new Set(
    existingSkus
      .filter((s): s is string => typeof s === 'string' && s.trim().length > 0)
      .map((s) => s.trim().toUpperCase())
  );

  const cleanPrefix = (prefix || 'PRD').replace(/[^A-Za-z0-9]/g, '').toUpperCase() || 'PRD';
  let formattedPrefix = cleanPrefix;

  if (name && name.trim()) {
    const words = name.trim().split(/\s+/).slice(0, 3);
    const initials = words
      .map((w) => w.replace(/[^A-Za-z0-9]/g, '').slice(0, 3).toUpperCase())
      .filter(Boolean)
      .join('');
    if (initials) {
      formattedPrefix = `${cleanPrefix}-${initials}`;
    }
  }

  // Attempt up to 200 random numbers to avoid any memory collision
  for (let i = 0; i < 200; i++) {
    const num = Math.floor(1000 + Math.random() * 9000);
    const candidate = `${formattedPrefix}-${num}`;
    if (!existingSet.has(candidate.toUpperCase())) {
      return candidate;
    }
  }

  // Fallback with timestamp slice
  return `${formattedPrefix}-${Date.now().toString().slice(-4)}`;
}

/**
 * Checks whether an SKU string matches standard auto-generated formats
 * (e.g. PRD-1234, PRD-LAP-5821, FU-001).
 */
export function isAutoGeneratedSku(sku?: string | null): boolean {
  if (!sku || !sku.trim()) return true;
  const s = sku.trim();
  return /^PRD(-[A-Z0-9]+)?-\d{4,}$/i.test(s) || /^FU-\d+$/i.test(s);
}
